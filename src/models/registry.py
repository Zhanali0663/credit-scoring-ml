"""Model factory - returns instantiated sklearn-compatible classifiers.

Optional tuned hyperparameters can be provided in ``configs/best_params.yaml``
generated by ``src.models.tuning`` - the factory will override constructor
defaults when a matching entry exists.
"""
from __future__ import annotations

from typing import Any

import yaml
from sklearn.ensemble import RandomForestClassifier
from sklearn.linear_model import LogisticRegression

from src.utils.config import get_project_root
from src.utils.logging import get_logger

logger = get_logger(__name__)

BEST_PARAMS_FILE = "best_params.yaml"


def _load_tuned_params() -> dict[str, dict[str, Any]]:
    """Return the tuned-params mapping from ``configs/best_params.yaml``, if any."""
    path = get_project_root() / "configs" / BEST_PARAMS_FILE
    if not path.exists():
        return {}
    try:
        with path.open("r", encoding="utf-8") as f:
            data = yaml.safe_load(f) or {}
        return data if isinstance(data, dict) else {}
    except yaml.YAMLError as exc:
        logger.warning("Could not parse %s: %s", path, exc)
        return {}


def _apply_tuned(name: str, kwargs: dict[str, Any]) -> dict[str, Any]:
    """Merge tuned hyperparameters (if present) into constructor kwargs."""
    tuned = _load_tuned_params().get(name)
    if not tuned:
        return kwargs
    if isinstance(tuned, dict) and "best_params" in tuned:
        tuned = tuned["best_params"]
    if not isinstance(tuned, dict):
        return kwargs
    logger.info("Using tuned hyperparameters for %s: %s", name, tuned)
    kwargs.update(tuned)
    # Never allow these to leak through
    if "use_label_encoder" in kwargs:
        kwargs.pop("use_label_encoder", None)
    return kwargs


def get_logistic_regression() -> LogisticRegression:
    """Return a baseline Logistic Regression classifier.

    Class weight is balanced to compensate for the imbalanced target.
    """
    return LogisticRegression(
        max_iter=2000,
        solver="liblinear",
        class_weight="balanced",
        random_state=42,
    )


def get_random_forest() -> RandomForestClassifier:
    """Return a baseline Random Forest classifier."""
    return RandomForestClassifier(
        n_estimators=500,
        max_depth=None,
        min_samples_split=4,
        min_samples_leaf=2,
        n_jobs=-1,
        class_weight="balanced",
        random_state=42,
    )


def get_xgboost() -> Any:
    """Return an XGBoost classifier with conservative defaults."""
    from xgboost import XGBClassifier

    kwargs = {
        "n_estimators": 600,
        "learning_rate": 0.05,
        "max_depth": 5,
        "subsample": 0.9,
        "colsample_bytree": 0.8,
        "objective": "binary:logistic",
        "eval_metric": "auc",
        "scale_pos_weight": 3.0,  # approx. neg/pos ratio for the default dataset
        "tree_method": "hist",
        "n_jobs": -1,
        "random_state": 42,
    }
    return XGBClassifier(**_apply_tuned("xgboost", kwargs))


def get_lightgbm() -> Any:
    """Return a LightGBM classifier with conservative defaults."""
    from lightgbm import LGBMClassifier

    kwargs = {
        "n_estimators": 800,
        "learning_rate": 0.03,
        "num_leaves": 31,
        "max_depth": -1,
        "subsample": 0.9,
        "colsample_bytree": 0.8,
        "objective": "binary",
        "class_weight": "balanced",
        "random_state": 42,
        "n_jobs": -1,
        "verbosity": -1,
    }
    return LGBMClassifier(**_apply_tuned("lightgbm", kwargs))


def get_catboost() -> Any:
    """Return a CatBoost classifier with conservative defaults."""
    from catboost import CatBoostClassifier

    kwargs = {
        "iterations": 800,
        "learning_rate": 0.05,
        "depth": 6,
        "l2_leaf_reg": 3.0,
        "loss_function": "Logloss",
        "eval_metric": "AUC",
        "auto_class_weights": "Balanced",
        "random_seed": 42,
        "verbose": False,
        "allow_writing_files": False,
    }
    return CatBoostClassifier(**_apply_tuned("catboost", kwargs))


MODEL_REGISTRY: dict[str, Any] = {
    "logistic_regression": get_logistic_regression,
    "random_forest": get_random_forest,
    "xgboost": get_xgboost,
    "lightgbm": get_lightgbm,
    "catboost": get_catboost,
}


def build_model(name: str):
    """Build a model by name."""
    if name not in MODEL_REGISTRY:
        raise ValueError(f"Unknown model: {name}. Available: {list(MODEL_REGISTRY)}")
    return MODEL_REGISTRY[name]()
